<h1>Licence Renewal Policy for {{LICENCE_NAME}}</h1>

<h3>1. Purpose</h3>
<p>This policy defines how licence renewals are handled for products purchased through {{WORDPRESS_SITENAME}}, including renewal timelines, payment requirements, grace periods, and consequences of non‑renewal.</p>

<h3>2. Renewal Eligibility</h3>
<p>A licence is eligible for renewal if:</p>
<ul>
<li>It is currently active, or</li>
<li>It is within the defined grace period after expiry.</li>
</ul>
<p>Expired licences outside the grace period may require a new purchase rather than a renewal.</p>

<h3>3. Renewal Term</h3>
<p>Renewals extend the licence for the same duration as the original licence term unless otherwise specified (e.g., 12 months, lifetime upgrades, multi‑year terms).</p>

<h3>4. Renewal Window</h3>
<p>Customers may renew:</p>
<ul>
<li>Up to {{LICENCE_RENEWAL_WINDOW}} days before the licence expiry date</li>
<li>Up to {{LICENCE_GRACE_PERIOD}} days after expiry (grace period)</li>
</ul>
<p>During the grace period, the licence remains functional unless the product defines otherwise.</p>

<h3>5. Grace Period</h3>
<p>The grace period allows customers to renew without losing activation status.</p>
<p>During this period:</p>
<ul>
<li>The licence remains valid</li>
<li>Updates and support continue</li>
<li>No new activations may be allowed (optional per product)</li>
</ul>
<p>If the grace period ends without renewal, the licence becomes fully expired.</p>

<h3>6. Renewal Pricing</h3>
<p>Renewal pricing is determined by the product vendor and may include:</p>
<ul>
<li>Standard renewal rate</li>
<li>Discounted early‑renewal rate</li>
<li>Lapsed‑renewal rate (optional)</li>
</ul>
<p>LicencePress stores and enforces the renewal price defined by the vendor at the time of renewal.</p>

<h3>7. Payment & Activation</h3>
<p>Upon successful payment:</p>
<ul>
<li>The licence term is extended</li>
<li>The renewal date becomes the new expiry date</li>
<li>All activation limits and entitlements reset according to the licence plan</li>
<li>A renewal confirmation email is sent automatically (if enabled)</li>
</ul>

<h3>8. Failed or Missed Renewals</h3>
<p>If renewal payment fails or the grace period expires:</p>
<ul>
<li>The licence becomes inactive</li>
<li>Updates and support may be restricted</li>
<li>Activations may be blocked or revoked depending on vendor settings</li>
<li>The customer may be required to purchase a new licence</li>
</ul>

<h3>9. Auto‑Renewal (Optional)</h3>
<p>If auto‑renewal is enabled:</p>
<ul>
<li>The system attempts renewal on the expiry date</li>
<li>Customers are notified of upcoming charges</li>
<li>Failed auto‑renewals trigger retry attempts and notifications</li>
</ul>

<h3>10. Changes to Renewal Policy</h3>
<p>{{LICENCEPRESS_LICENSOR}} may update renewal rules at any time.</p>
<p>Changes do not affect licences already renewed but apply to future renewals.</p>